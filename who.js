// WHO reference anchors (months 0,6,12,18,24,36,48,60) used by seed.js to classify demo data
const M = [0, 6, 12, 18, 24, 36, 48, 60];
const D = {
  hB: [[49.9,46.1,44.2],[67.6,63.3,61.2],[75.7,71.0,68.6],[82.3,76.9,74.0],[87.8,81.0,78.0],[96.1,89.2,85.0],[103.3,94.9,90.7],[110.0,100.7,96.1]],
  hG: [[49.1,45.4,43.6],[65.7,61.2,58.9],[74.0,68.9,66.3],[80.7,74.9,72.0],[86.4,80.0,76.7],[95.1,88.7,84.1],[102.7,94.1,89.8],[109.4,99.9,95.2]],
  wB: [[3.3,2.5,2.1,4.4],[7.9,6.4,5.7,9.8],[9.6,7.7,6.9,12.0],[10.9,8.8,7.8,13.7],[12.2,9.7,8.6,15.3],[14.3,11.3,10.0,18.3],[16.3,12.7,11.2,21.2],[18.3,14.1,12.4,24.2]],
  wG: [[3.2,2.4,2.0,4.2],[7.3,5.7,5.0,9.3],[8.9,7.0,6.1,11.5],[10.2,8.1,7.1,13.2],[11.5,9.0,8.0,14.8],[13.9,10.8,9.5,18.1],[16.1,12.3,10.8,21.5],[18.2,13.7,11.8,24.9]]
};
function ref(key, m) {
  let i = 0; while (i < M.length - 2 && m > M[i + 1]) i++;
  const f = (m - M[i]) / (M[i + 1] - M[i]);
  return D[key][i].map((v, j) => v + (D[key][i + 1][j] - v) * f);
}
// ch: 0 normal,1 stunted,2 severely stunted | cw: 0 normal,1 underweight,2 severe,3 overweight
function classify(k, m, h, w) {
  const rh = ref("h" + k, m), rw = ref("w" + k, m);
  return { ch: h < rh[2] ? 2 : h < rh[1] ? 1 : 0, cw: w < rw[2] ? 2 : w < rw[1] ? 1 : w > rw[3] ? 3 : 0 };
}
module.exports = { classify };
